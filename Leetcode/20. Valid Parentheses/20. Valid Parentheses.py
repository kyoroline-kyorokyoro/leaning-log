class Solution:
    def isValid(self, s: str) -> bool:
        stack=[]

        brackets_pair={")":"(","]":"[","}":"{"}

        for char in s:
            if char in brackets_pair.values():
                stack.append(char)
            
            else:
                if not stack or stack[-1]!=brackets_pair[char]:
                    return False
                else:stack.pop()
        return not stack
    
#      正しく閉じるための条件
# 開きカッコに対して、正しい閉じカッコがある。
# カッコが正しい順序でネストされている。
# すべてのカッコが使われてスタックが空になること。

# 考え方
# スタック（後入れ先出し）を使う。
# 開きカッコが来たらスタックに積む。
# 閉じカッコが来たら：
# スタックの一番上を取り出す。
# 対応する開きカッコと一致するかを確認。
# 最後にスタックが空なら True、
# 空でなければ False。

# ポイント解説
# 🔥 スタックを使う理由
# カッコは後から開いたものが先に閉じる必要がある。
# → つまり後入れ先出し (LIFO) が必要。
# スタックはこれを自然に表現できるデータ構造。

# 🔥 なぜ閉じカッコをキーにするの？
# 閉じカッコが来たとき、
# 対応する開きカッコをすぐに知りたい。
# 閉じカッコ→開きカッコの**マッピング（辞書）**を作っておけば、
# 一発でチェックできる。

# なぜ最後に return not stack ？
# Pythonではリストが空なら False。
# not stack なら、空リストならTrue。
# カッコが正しく閉じられていれば、スタックは空になっている。

# 🚨 注意するポイント
# スタックが空なのに閉じカッコが来た → False
# 閉じカッコとスタックトップが一致しない → False
# 最後にスタックに何か残ってる → False

#  まとめ
# スタックを使ってカッコの正しさをチェックする。
# 閉じカッコをキーにして、対応する開きカッコをすぐに確認。
# 最後にスタックが空なら、全てのカッコが正しくペアになっていたことが保証される。